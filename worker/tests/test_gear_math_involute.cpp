//     structurally distinct branches this port's test cases exercise:
//       - !undercut, dg > df   (5 segments, root-blend synthetic point)
//       - undercut, nearestpts fallback (5 segments, variable u1 length)
//       - !undercut, dg <= df  (3 segments, no root blend)
//     The `trimfunc`-crossing-found branch is implemented (see
//     InvoluteMath.cpp) but not exercised by any case here — no parameter
//     combination tried during oracle generation made the sampled undercut
//     and involute polylines actually cross. Flagged, not silently assumed
//     correct: a future case that DOES cross should be added here before
//     that branch is trusted for a real undercut gear.
