int main() {
    for (const auto& c : kCases) {
        const gear::InvoluteFactorsResult r = gear::compute_involute_factors(c.params);
        CHECK(r.ok);
        if (!r.ok) {
            std::fprintf(stderr, "  (case %s error: %s)\n", c.name, r.error.c_str());
            continue;
        }
        const gear::InvoluteToothFactors& f = r.factors;
        CHECK_NEAR(f.pressureAngleTransverse, c.pressureAngleTransverse, "pressureAngleTransverse", c.name);
        CHECK_NEAR(f.transverseModule, c.transverseModule, "transverseModule", c.name);
        CHECK_NEAR(f.transversePitch, c.transversePitch, "transversePitch", c.name);
        CHECK_NEAR(f.clearanceAbs, c.clearanceAbs, "clearanceAbs", c.name);
        CHECK_NEAR(f.referenceDiameter, c.referenceDiameter, "referenceDiameter", c.name);
        CHECK_NEAR(f.workingDiameter, c.workingDiameter, "workingDiameter", c.name);
        CHECK_NEAR(f.addendumDiameter, c.addendumDiameter, "addendumDiameter", c.name);
        CHECK_NEAR(f.rootDiameter, c.rootDiameter, "rootDiameter", c.name);
        CHECK_NEAR(f.baseDiameter, c.baseDiameter, "baseDiameter", c.name);
        CHECK_NEAR(f.angularPitch, c.angularPitch, "angularPitch", c.name);
        CHECK_NEAR(f.undercutEnd, c.undercutEnd, "undercutEnd", c.name);
        CHECK_NEAR(f.undercutRot, c.undercutRot, "undercutRot", c.name);
        CHECK_NEAR(f.involuteEnd, c.involuteEnd, "involuteEnd", c.name);
        CHECK_NEAR(f.involuteRot1, c.involuteRot1, "involuteRot1", c.name);
        CHECK_NEAR(f.involuteRot2, c.involuteRot2, "involuteRot2", c.name);
        CHECK_NEAR(f.involuteRot, c.involuteRot, "involuteRot", c.name);
        CHECK_NEAR(f.angularBacklash, c.angularBacklash, "angularBacklash", c.name);
        CHECK_NEAR(f.involuteStart, c.involuteStart, "involuteStart", c.name);

        const auto invPts = gear::involute_points(f, 7);
        CHECK(invPts.size() == 7);
        CHECK_POINT_NEAR(invPts.front(), c.involFirst, "involute_points[0]", c.name);
        CHECK_POINT_NEAR(invPts.back(), c.involLast, "involute_points[6]", c.name);

        const auto uncPts = gear::undercut_points(f, 7);
        CHECK(uncPts.size() == 7);
        CHECK_POINT_NEAR(uncPts.front(), c.undercutFirst, "undercut_points[0]", c.name);
        CHECK_POINT_NEAR(uncPts.back(), c.undercutLast, "undercut_points[6]", c.name);
    }

    for (const auto& c : kToothCases) {
        const gear::InvoluteFactorsResult r = gear::compute_involute_factors(c.params);
        CHECK(r.ok);
        if (!r.ok) {
            std::fprintf(stderr, "  (tooth case %s error: %s)\n", c.name, r.error.c_str());
            continue;
        }
        const gear::ToothProfile profile =
            gear::one_tooth_profile(c.params, r.factors, c.sampleCount);
        CHECK(profile.segments.size() == c.segments.size());
        if (profile.segments.size() != c.segments.size()) {
            std::fprintf(stderr, "  (tooth case %s: got %zu segments, expected %zu)\n", c.name,
                         profile.segments.size(), c.segments.size());
            continue;
        }
        for (std::size_t s = 0; s < c.segments.size(); ++s) {
            CHECK(profile.segments[s].size() == c.segments[s].size());
            if (profile.segments[s].size() != c.segments[s].size()) {
                std::fprintf(stderr, "  (tooth case %s segment %zu: got %zu points, expected %zu)\n",
                             c.name, s, profile.segments[s].size(), c.segments[s].size());
                continue;
            }
            for (std::size_t i = 0; i < c.segments[s].size(); ++i) {
                char what[64];
                std::snprintf(what, sizeof(what), "segment[%zu][%zu]", s, i);
                CHECK_POINT_NEAR(profile.segments[s][i], c.segments[s][i], what, c.name);
            }
        }
        // Continuity invariant every branch must hold regardless of oracle
        // coverage: each segment's last point equals the next segment's
        // first point (this is what lets a wire builder concatenate them).
        for (std::size_t s = 0; s + 1 < profile.segments.size(); ++s) {
            const auto& a = profile.segments[s].back();
            const auto& b = profile.segments[s + 1].front();
            CHECK(std::abs(a.x - b.x) < 1e-9 && std::abs(a.y - b.y) < 1e-9);
        }
    }

    // --- Domain refusal matrix: bad params must fail closed with a message,
    //     never silently produce NaN factors (see InvoluteMath.h). ---
    {
        gear::InvoluteToothParams p;
        p.numTeeth = 2;
        const auto r = gear::compute_involute_factors(p);
        CHECK(!r.ok);
        CHECK(!r.error.empty());
    }
    {
        gear::InvoluteToothParams p;
        p.module = 0.0;
        const auto r = gear::compute_involute_factors(p);
        CHECK(!r.ok);
    }
    {
        gear::InvoluteToothParams p;
        p.pressureAngle = 0.0;
        const auto r = gear::compute_involute_factors(p);
        CHECK(!r.ok);
    }
    {
        gear::InvoluteToothParams p;
        p.pressureAngle = kPi / 2.0;
        const auto r = gear::compute_involute_factors(p);
        CHECK(!r.ok);
    }
    {
        // Extreme negative shift can push the root diameter non-positive.
        gear::InvoluteToothParams p;
        p.numTeeth = 5;
        p.shift = -5.0;
        const auto r = gear::compute_involute_factors(p);
        CHECK(!r.ok);
    }
    // A sane default set must still succeed (negative control for the
    // refusal matrix above).
    {
        gear::InvoluteToothParams p;  // defaults: m=5, z=15, 20deg, shift=0, clearance=0.25
        const auto r = gear::compute_involute_factors(p);
        CHECK(r.ok);
    }

    if (g_failures == 0) {
        std::fprintf(stderr, "OK: gear_math_involute\n");
    }
    // Exit status is 8-bit on POSIX, so returning a raw failure count reports
    // SUCCESS whenever that count is a multiple of 256 — this file's sweeps
    // can produce thousands. Clamp to a nonzero cap so a failing run can never
    // masquerade as a passing one, while small counts stay readable.
    return (g_failures == 0) ? 0 : (g_failures > 100 ? 100 : g_failures);
}
