// test_gear_math_involute.cpp — external involute gear tooth math, checked
// against a real oracle: values computed by RUNNING the actual upstream
// `pygears.involute_tooth.InvoluteTooth` (freecad.gears v1.3.0, GPL-3.0,
// commit pinned to the `master` branch as fetched during the Gear Generator
// implementation plan's G0 phase), not re-derived by hand. This is the
// project's cross-check-harness posture (Gear Generator plan §10.1 leg 2)
// applied at unit-test scale: a formula transcription bug shows up here as a
// tolerance failure, not as "my C++ agrees with my own re-derivation."
//
// No test framework (matches the prototype style, see test_polygon_fill.cpp):
// exit code == failure count.
