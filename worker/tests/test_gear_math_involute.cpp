int g_failures = 0;
#define CHECK(cond)                                                              \
    do {                                                                         \
        if (!(cond)) {                                                           \
            std::fprintf(stderr, "FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond); \
            ++g_failures;                                                        \
        }                                                                        \
    } while (0)

constexpr double kPi = 3.14159265358979323846;
constexpr double kTol = 1e-7;

void CHECK_NEAR(double actual, double expected, const char* what, const char* caseName) {
    if (std::abs(actual - expected) > kTol) {
        std::fprintf(stderr, "FAIL %s: %s mismatch: actual=%.12f expected=%.12f (case %s)\n",
                     __FILE__, what, actual, expected, caseName);
        ++g_failures;
    }
}

void CHECK_POINT_NEAR(const gear::Point2d& actual, const gear::Point2d& expected,
                       const char* what, const char* caseName) {
    if (std::abs(actual.x - expected.x) > kTol || std::abs(actual.y - expected.y) > kTol) {
        std::fprintf(stderr,
                     "FAIL %s: %s mismatch: actual=(%.12f,%.12f) expected=(%.12f,%.12f) (case %s)\n",
                     __FILE__, what, actual.x, actual.y, expected.x, expected.y, caseName);
        ++g_failures;
    }
}

double deg(double d) { return d * kPi / 180.0; }

