#pragma once

// Slot-claim rewrites for FeaturePattern instance refs (internal; header-only so
// the rules are unit-testable without a ScratchJob).
#include <set>
#include <string>

#include "nlohmann/json.hpp"
#include "session/FeaturePattern.h"

namespace onecad::session {

// ONECAD-361: a ref frozen on one hole of a multi-point Hole names its producer
// record in `intent.descriptor.originSlot`. Inside an instance that producer
// ran under its virtual opId, so the claim must name that id too; a producer
// outside the selected sources keeps its own.
inline void rewrite_origin_slot(nlohmann::json& descriptor, const std::string& pattern,
                                int instance, const std::set<std::string>& selected_ids) {
    if (!descriptor.is_object() || !descriptor.contains("originSlot") ||
        !descriptor["originSlot"].is_object())
        return;
    nlohmann::json& origin = descriptor["originSlot"];
    if (!origin.contains("recordId") || !origin["recordId"].is_string()) return;
    const std::string producer = origin["recordId"].get<std::string>();
    if (selected_ids.contains(producer))
        origin["recordId"] = feature_pattern_virtual_id(pattern, producer, instance);
}

// SCHEMA §7.5 `generatorSlot`: same producer rule, but an unselected producer's
// claim is ERASED (also when malformed) — the instance edge was not generated by
// it, and keeping it would narrow the instance ref onto the source's own edge.
inline void rewrite_generator_slot(nlohmann::json& descriptor, const std::string& pattern,
                                   int instance, const std::set<std::string>& selected_ids) {
    if (!descriptor.is_object() || !descriptor.contains("generatorSlot")) return;
    nlohmann::json& generator = descriptor["generatorSlot"];
    if (generator.is_object() && generator.contains("recordId") &&
        generator["recordId"].is_string()) {
        const std::string producer = generator["recordId"].get<std::string>();
        if (selected_ids.contains(producer)) {
            generator["recordId"] = feature_pattern_virtual_id(pattern, producer, instance);
            return;
        }
    }
    descriptor.erase("generatorSlot");
}

// Both rewrites for one input ref. A shared host face keeps the source ref
// verbatim (it is not transformed either), so its claims are left unchanged.
inline void rewrite_ref_slot_claims(nlohmann::json& ref, const std::string& pattern,
                                    int instance, bool shared_host_face,
                                    const std::set<std::string>& selected_ids) {
    if (shared_host_face || !ref.is_object() || !ref.contains("intent") ||
        !ref["intent"].is_object() || !ref["intent"].contains("descriptor"))
        return;
    rewrite_origin_slot(ref["intent"]["descriptor"], pattern, instance, selected_ids);
    rewrite_generator_slot(ref["intent"]["descriptor"], pattern, instance, selected_ids);
}

}  // namespace onecad::session
