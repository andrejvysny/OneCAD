//! Generates the Slint theme and the viewport palette from `src/styles/tokens.css`, so the CSS
//! stays the single color source (plan Phase 4 "a build step generates the Rust theme tokens"),
//! then compiles the .slint UI.

use std::collections::BTreeMap;
use std::path::PathBuf;

const TOKENS: &str = "../../src/styles/tokens.css";

/// `--color-<name>: <value>;` pairs inside the block that starts at `open`.
fn block(css: &str, open: &str) -> BTreeMap<String, [u8; 4]> {
    let mut out = BTreeMap::new();
    let Some(start) = css.find(open) else {
        return out;
    };
    let body = &css[start + open.len()..];
    let body = &body[..body.find("\n}").unwrap_or(body.len())];
    for line in body.lines() {
        let line = line.trim();
        let Some(rest) = line.strip_prefix("--color-") else {
            continue;
        };
        let Some((name, value)) = rest.split_once(':') else {
            continue;
        };
        if let Some(rgba) = parse_color(value.trim().trim_end_matches(';')) {
            out.insert(name.trim().to_string(), rgba);
        }
    }
    out
}

fn parse_color(v: &str) -> Option<[u8; 4]> {
    if let Some(hex) = v.strip_prefix('#') {
        let n = u32::from_str_radix(hex, 16).ok()?;
        return (hex.len() == 6).then_some([(n >> 16) as u8, (n >> 8) as u8, n as u8, 255]);
    }
    // rgb(r g b / a)
    let inner = v.strip_prefix("rgb(")?.strip_suffix(')')?;
    let (rgb, a) = inner.split_once('/').unwrap_or((inner, "1"));
    let c: Vec<u8> = rgb
        .split_whitespace()
        .filter_map(|x| x.parse().ok())
        .collect();
    let a: f32 = a.trim().parse().ok()?;
    (c.len() == 3).then(|| [c[0], c[1], c[2], (a * 255.0).round() as u8])
}

fn main() {
    println!("cargo:rerun-if-changed={TOKENS}");
    println!("cargo:rerun-if-changed=ui");
    let css = std::fs::read_to_string(TOKENS).expect("read tokens.css");
    let mut dark = block(&css, "@theme {");
    dark.extend(block(&css, ":root[data-theme=\"dark\"] {"));
    assert!(
        dark.len() > 60,
        "tokens.css parse found only {} colors",
        dark.len()
    );

    let mut slint = String::from("// @generated by build.rs from src/styles/tokens.css (dark)\n");
    slint.push_str("export global Tokens {\n");
    let mut rust = String::from("// @generated by build.rs from src/styles/tokens.css (dark)\n");
    rust.push_str("pub const DARK: &[(&str, [u8; 4])] = &[\n");
    for (name, [r, g, b, a]) in &dark {
        slint.push_str(&format!(
            "    out property <color> {name}: #{r:02x}{g:02x}{b:02x}{a:02x};\n"
        ));
        rust.push_str(&format!("    (\"{name}\", [{r}, {g}, {b}, {a}]),\n"));
    }
    slint.push_str("}\n");
    rust.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out.join("tokens.slint"), slint).expect("write tokens.slint");
    std::fs::write(out.join("tokens.rs"), rust).expect("write tokens.rs");

    let config = slint_build::CompilerConfiguration::new()
        .with_include_paths(vec![out.clone()])
        .with_style("fluent-dark".into());
    slint_build::compile_with_config("ui/app.slint", config).expect("compile ui/app.slint");
}
